doc = Document()
st = doc.styles["Normal"]
st.font.name = "Noto Sans CJK KR"
st.font.size = Pt(10.5)

C = WD_ALIGN_PARAGRAPH.CENTER


def para(text, bold=False, size=None, align=None):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    r = p.add_run(text)
    r.bold = bold
    if size:
        r.font.size = Pt(size)
    return p


def caption(text):
    para(text, size=9.5, align=C)


def table(rows, header=True, widths=None, font=9.5):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = doc.styles["Table Grid"]
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = C
            r = p.add_run(str(val))
            r.font.size = Pt(font)
            if header and i == 0:
                r.bold = True
    return t


def figure(path, caption_text, width=5.9):
    p = doc.add_paragraph()
    p.alignment = C
    p.add_run().add_picture(str(path), width=Inches(width))
    caption(caption_text)


