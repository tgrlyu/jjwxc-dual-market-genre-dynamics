para("This study analyzes 3,856,274 catalog metadata records collected from Jinjiang Literature City (2003–2026) by decomposing the platform's catalog into two fully separated markets: original works (原创) and derivative works (衍生). Four findings emerge. First, in the original market, the share of romance (爱情) declined from its 2010 peak of 88.2% to 56.4% in 2024, with the drama genre (剧情) absorbing the decline and rising to 14.6%. Second, the derivative market underwent a distinct restructuring: Chinese-source fanfiction (东方衍生) held 85–96% of the market from 2009 to 2017, then collapsed within two years—from 85.0% in 2017 to 30.6% in 2019—as fandom sources diversified toward Japanese ACGN and other global origins. Third, title keywords operate as a dual system of conventions, standardizing metanarrative devices (rebirth, quick transmigration, book transmigration) while absorbing Chinese internet buzzwords within roughly one year of their social emergence. Fourth, the platform's creator base is a hyper-churn pool—85–95% of active authors in each period are period debutants, with 3–9% inter-period retention—while reception concentrates in a superstar structure, with the top 1% of works capturing 65.6% to 75.0% of total reception points. Methodologically, the study empirically demonstrates that year-filter-based 'exhaustive' collection systematically omits undated serializing works (omission rate 0.13% for completed vs. 12.8–14.5% for serializing works), undercounting recent years. Platform search axes are institutional constructs requiring validation, not neutral windows of observation.")
